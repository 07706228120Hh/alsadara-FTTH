/// مقاسات ثابتة لوحدة «وكيل الساس» — بديل محلّي لامتدادات `flutter_screenutil`.
///
/// السبب: الوحدة تُستخدم أساساً على **سطح المكتب** (نوافذ عريضة ~1600–1900px)،
/// بينما `ScreenUtilInit` مضبوط على `designSize = 375×812` (مقاس هاتف). عندها
/// تتضخّم امتدادات `.sp/.w/.h/.r` بمعامل يقارب `عرض_النافذة / 375` (≈ ×4–×5)،
/// فتتحوّل عناوين 15sp إلى ~60–75px تفيض حاوياتها (تظهر كشُرَط/نقاط أو تتصادم
/// مع شريط التبويبات في الأعلى)، وترتفع الحاويات/الهوامش بشكل مبالغ.
///
/// الحل: نستبدل استيراد `package:flutter_screenutil/flutter_screenutil.dart`
/// بهذا الملف في كل ملفات `lib/sas_agent/**`. الامتدادات هنا **تُرجِع القيمة
/// الخام كما هي** (هوية)، فتصبح كل الأرقام مقاسات ثابتة معقولة على كل المنصّات
/// (قيم تصميم الأساس 375 مناسبة للهاتف، ومقروءة على سطح المكتب بلا تضخّم).
///
/// بهذا لا نُعيد كتابة ~900 موضع استدعاء؛ يكفي تبديل الاستيراد، ويبقى الكود
/// القائم (`14.sp`، `10.w`، `12.h`، `16.r`) يعمل لكن بمقاس ثابت.
library;

/// امتدادات مقاس ثابتة على [num] تطابق أسماء امتدادات ScreenUtil لكنها
/// تُرجِع القيمة الخام (بلا أي تحجيم حسب عرض الشاشة).
extension SasFixedMetrics on num {
  /// عرض ثابت (بديل `ScreenUtil.setWidth`).
  double get w => toDouble();

  /// ارتفاع ثابت (بديل `ScreenUtil.setHeight`).
  double get h => toDouble();

  /// حجم خط ثابت (بديل `ScreenUtil.setSp`).
  double get sp => toDouble();

  /// نصف قطر/زاوية ثابتة (بديل `ScreenUtil.radius`).
  double get r => toDouble();
}
